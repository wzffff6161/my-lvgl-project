/* 按 Unicode 码点查点阵下标，找不到返回 -1（仅 80 字，线性查找即可） */
static int chinese_font_lookup(uint32_t letter)
{
    for (int i = 0; i < CHINESE_FONT_GLYPH_COUNT; i++) {
        if (g_chinese_unicode[i] == letter) {
            return i;
        }
    }
    return -1;
}

static bool chinese_font_get_glyph_dsc(const lv_font_t *font, lv_font_glyph_dsc_t *dsc,
                                       uint32_t letter, uint32_t letter_next)
{
    (void)font;
    (void)letter_next;

    if (chinese_font_lookup(letter) < 0) {
        return false;   /* 交给 fallback 字体处理 */
    }

    dsc->adv_w = 16;
    dsc->box_w = 16;
    dsc->box_h = 16;
    dsc->ofs_x = 0;
    dsc->ofs_y = 0;
    dsc->bpp = 1;
    dsc->is_placeholder = 0;   /* 必须显式清零，否则位域未初始化会干扰 lv_font.c 的 fallback 判定 */
    return true;
}

static const uint8_t *chinese_font_get_glyph_bitmap(const lv_font_t *font, uint32_t letter)
{
    (void)font;

    int idx = chinese_font_lookup(letter);
    if (idx < 0) {
        return NULL;
    }
    return g_chinese_bitmap[idx];
}

